"""Application configuration management using Pydantic Settings."""

from functools import lru_cache
from typing import List
from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Central application settings loaded from environment variables and .env file."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
    )

    # Application Core
    PROJECT_NAME: str = "PalmMind AI - Document RAG & Interview Booking Assistant"
    VERSION: str = "0.1.0"
    ENVIRONMENT: str = "development"
    DEBUG: bool = True
    API_V1_PREFIX: str = "/api/v1"
    HOST: str = "0.0.0.0"
    PORT: int = 8000
    LOG_LEVEL: str = "INFO"

    # LLM Settings (Google Gemini)
    GEMINI_API_KEY: str = Field(default="", description="Google Gemini API key")
    GEMINI_MODEL: str = Field(default="gemini-2.5-flash", description="Gemini model identifier")

    # Embedding Model Settings (Sentence Transformers)
    EMBEDDING_MODEL_NAME: str = Field(
        default="all-MiniLM-L6-v2",
        description="Local sentence-transformers embedding model name",
    )
    EMBEDDING_DIMENSION: int = Field(
        default=384,
        description="Dimensionality of embeddings generated by all-MiniLM-L6-v2",
    )

    # Vector Database Settings (Qdrant)
    QDRANT_HOST: str = Field(default="localhost", description="Qdrant service host")
    QDRANT_PORT: int = Field(default=6333, description="Qdrant REST port")
    QDRANT_GRPC_PORT: int = Field(default=6334, description="Qdrant gRPC port")
    QDRANT_COLLECTION: str = Field(
        default="palmind_docs",
        description="Default Qdrant collection name",
    )

    # Conversational Memory Settings (Redis)
    REDIS_HOST: str = Field(default="localhost", description="Redis host")
    REDIS_PORT: int = Field(default=6379, description="Redis port")
    REDIS_DB: int = Field(default=0, description="Redis database index")
    REDIS_SESSION_TTL_SECONDS: int = Field(
        default=86400,
        description="Redis session expiration time in seconds (default: 24h)",
    )
    REDIS_HISTORY_LIMIT: int = Field(
        default=10,
        description="Number of past turns to retrieve for context construction",
    )

    # Relational Database Settings (SQLite)
    DATABASE_URL: str = Field(
        default="sqlite:///./palmind.db",
        description="SQLAlchemy database connection URL",
    )

    # File Ingestion Constraints
    MAX_UPLOAD_SIZE_MB: int = Field(
        default=10,
        description="Maximum allowed file upload size in megabytes",
    )
    ALLOWED_FILE_TYPES: List[str] = Field(
        default=["pdf", "txt"],
        description="Permitted file extensions for ingestion",
    )

    # Chunking Defaults
    DEFAULT_FIXED_CHUNK_SIZE: int = 500
    DEFAULT_FIXED_CHUNK_OVERLAP: int = 50
    DEFAULT_RECURSIVE_CHUNK_SIZE: int = 500
    DEFAULT_RECURSIVE_CHUNK_OVERLAP: int = 50


@lru_cache
def get_settings() -> Settings:
    """Return a cached singleton instance of application settings."""
    return Settings()

